create table public.person_operational_capabilities (
  person_id bigint not null references public.people(id) on delete cascade,
  capability_type_id smallint not null references public.operational_capability_types(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (person_id, capability_type_id)
);

create table public.calendar_periods (
  id bigint generated by default as identity primary key,
  unit_id bigint not null references public.units(id) on delete cascade,
  year smallint not null check (year between 2020 and 2100),
  month smallint not null check (month between 1 and 12),
  status text not null default 'draft' check (status in ('draft', 'published')),
  created_by bigint not null references public.people(id),
  published_by bigint references public.people(id),
  published_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (unit_id, year, month)
);
create index calendar_periods_unit_date_idx on public.calendar_periods(unit_id, year, month);

create table public.calendar_day_notes (
  id bigint generated by default as identity primary key,
  unit_id bigint not null references public.units(id) on delete cascade,
  date date not null,
  note text not null check (char_length(note) between 1 and 240),
  updated_by bigint not null references public.people(id),
  updated_at timestamptz not null default now(),
  unique (unit_id, date)
);
create index calendar_day_notes_unit_date_idx on public.calendar_day_notes(unit_id, date);

create table public.calendar_assignments (
  id bigint generated by default as identity primary key,
  unit_id bigint not null references public.units(id) on delete cascade,
  date date not null,
  assignment_type_id smallint not null references public.calendar_assignment_types(id),
  class_type_id smallint references public.calendar_class_types(id),
  person_id bigint not null references public.people(id),
  manually_assigned boolean not null default false,
  created_by bigint not null references public.people(id),
  updated_by bigint not null references public.people(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check ((assignment_type_id = 3 and class_type_id is null) or (assignment_type_id in (1, 2)))
);
create unique index calendar_assignments_slot_idx
  on public.calendar_assignments(unit_id, date, assignment_type_id, coalesce(class_type_id, 0));
create index calendar_assignments_unit_date_idx on public.calendar_assignments(unit_id, date);
create index calendar_assignments_person_date_idx on public.calendar_assignments(person_id, date);


create policy person_operational_capabilities_read on public.person_operational_capabilities
  for select to authenticated using (
    person_id = private.current_person_id()
    or exists (
      select 1 from public.unit_memberships mine
      join public.unit_memberships theirs on theirs.unit_id = mine.unit_id
      where mine.person_id = private.current_person_id()
        and theirs.person_id = person_operational_capabilities.person_id
    )
  );
create policy person_operational_capabilities_manage on public.person_operational_capabilities
  for all to authenticated using (private.is_manager()) with check (private.is_manager());


create table public.student_calendar_notes (
  id bigint generated by default as identity primary key,
  unit_id bigint not null references public.units(id) on delete cascade,
  date date not null,
  note text not null check (char_length(note) <= 240),
  category text not null default 'event' check (category in ('event','workshop','holiday','notice')),
  updated_by bigint not null references public.people(id),
  updated_at timestamptz not null default now(),
  unique(unit_id,date)
);
create index student_calendar_notes_updated_by_idx on public.student_calendar_notes(updated_by);
alter table public.student_calendar_notes enable row level security;
create policy student_calendar_notes_read on public.student_calendar_notes for select to authenticated using (private.is_unit_manager(unit_id));
create policy student_calendar_notes_insert on public.student_calendar_notes for insert to authenticated with check (private.is_unit_manager(unit_id));
create policy student_calendar_notes_update on public.student_calendar_notes for update to authenticated using (private.is_unit_manager(unit_id)) with check (private.is_unit_manager(unit_id));
create policy student_calendar_notes_delete on public.student_calendar_notes for delete to authenticated using (private.is_unit_manager(unit_id));
grant select,insert,update,delete on public.student_calendar_notes to authenticated;
grant usage,select on sequence public.student_calendar_notes_id_seq to authenticated;

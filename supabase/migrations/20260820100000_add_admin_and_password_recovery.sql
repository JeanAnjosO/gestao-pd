create or replace function private.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $function$
  select exists (
    select 1 from public.people
    where auth_user_id = (select auth.uid())
      and access_role_type_id = 5
      and active
  )
$function$;

create or replace function private.is_manager()
returns boolean
language sql
stable
security definer
set search_path = ''
as $function$
  select exists (
    select 1 from public.people
    where auth_user_id = (select auth.uid())
      and access_role_type_id in (1, 5)
      and active
  )
$function$;

create or replace function private.is_unit_manager(target_unit_id bigint)
returns boolean
language sql
stable
security definer
set search_path = ''
as $function$
  select exists (
    select 1
    from public.people p
    join public.unit_memberships um on um.person_id = p.id
    where p.auth_user_id = (select auth.uid())
      and p.access_role_type_id in (1, 5)
      and p.active
      and um.unit_id = target_unit_id
  )
$function$;

create table public.password_recovery_requests (
  id bigint generated by default as identity primary key,
  person_id bigint not null references public.people(id) on delete cascade,
  username_snapshot text not null,
  status text not null default 'pending' check (status in ('pending', 'completed', 'cancelled')),
  requested_at timestamptz not null default now(),
  expires_at timestamptz not null default (now() + interval '24 hours'),
  completed_at timestamptz,
  completed_by bigint references public.people(id),
  created_at timestamptz not null default now()
);

create unique index password_recovery_requests_one_pending_idx
  on public.password_recovery_requests(person_id)
  where status = 'pending';
create index password_recovery_requests_status_requested_idx
  on public.password_recovery_requests(status, requested_at desc);
create index password_recovery_requests_completed_by_idx
  on public.password_recovery_requests(completed_by);

alter table public.password_recovery_requests enable row level security;

create policy password_recovery_requests_admin_read
  on public.password_recovery_requests for select to authenticated
  using (private.is_admin());
create policy password_recovery_requests_admin_update
  on public.password_recovery_requests for update to authenticated
  using (private.is_admin()) with check (private.is_admin());

grant select, update on public.password_recovery_requests to authenticated;
grant usage, select on sequence public.password_recovery_requests_id_seq to authenticated;
